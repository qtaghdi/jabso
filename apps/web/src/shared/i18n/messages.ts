export type Locale = 'en' | 'ko'

const dictionaries: Record<Locale, Record<MessageKey, string>> = {
  en: englishMessages,
  ko: koreanMessages,
}

const pluralPattern = /\{(\w+), plural, one \{([^{}]*)\} other \{([^{}]*)\}\}/g
const valuePattern = /\{(\w+)\}/g

export const translate = (locale: Locale, key: MessageKey, values: MessageValues = {}) => {
  const message = dictionaries[locale][key]
  return message
    .replace(pluralPattern, (_match, name: string, one: string, other: string) => Number(values[name]) === 1 ? one : other)
    .replace(valuePattern, (_match, name: string) => String(values[name] ?? `{${name}}`))
}
